import assert from "node:assert/strict";
import { createDiagnostics, OUTCOMES } from "../src/engine/diagnostics.js";
let time = 100;
const d = createDiagnostics({ clock: () => time, limit: 3 });
const field = { el: {}, kind: "text", rawLabel: "PRIVATE_QUESTION", value: "PRIVATE_ANSWER", name: "PRIVATE_NAME" };
d.begin("top"); d.record({ field, stage: "rules", outcome: "answer_ready" });
assert.deepEqual(d.snapshot().events, [], "disabled diagnostics retain nothing");
d.configure(true); d.begin("child"); time += 7;
d.record({ field, stage: "rules", outcome: "answer_ready", reason: "PRIVATE_REASON", source: "PRIVATE_SOURCE", label: field.rawLabel, value: field.value });
const event = d.snapshot().events[1];
assert.equal(event.ms, 7, "stage time uses the injected clock");
assert.equal(JSON.stringify(d.snapshot()).includes("PRIVATE"), false, "allowlist drops all raw personal text");
assert.equal(event.reason, null, "unknown reason is never retained");
assert.equal(event.extractionSource, null, "unknown extractor signal is never retained");
d.record({ field, stage: "widgets", outcome: "write_reported" });
d.record({ field, stage: "review", outcome: "observed_nonempty" });
assert.equal(d.snapshot().events.length, 3, "ring is bounded");
assert.equal(d.snapshot().dropped, 1, "truncation is reported");
assert.equal(d.snapshot().events[0].fieldId, d.snapshot().events[1].fieldId, "field identity is consistent within frame");
const copy = d.snapshot(); copy.events[0].stage = "changed";
assert.notEqual(d.snapshot().events[0].stage, "changed", "exports cannot mutate the retained trace");
d.record({ field, stage: "rules", outcome: "PRIVATE_OUTCOME" });
assert.equal(d.snapshot().events.length, 3, "invalid outcome is rejected");
d.configure(false);
assert.deepEqual(d.snapshot(), { version: 1, enabled: false, dropped: 0, events: [] }, "turning off clears records");
assert.equal(OUTCOMES.includes("verified"), true);
console.log("diagnostics: 12 assertions passed");
