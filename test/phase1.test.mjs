const waitUntil = async (predicate) => { for (let i = 0; i < 100; i++) { if (await predicate()) return; await new Promise((r) => setTimeout(r, 10)); } throw new Error("Job did not settle"); };
function makeJobs(overrides = {}, initial = {}) {
  let data = structuredClone(initial), dispatches = 0;
  const storage = { get: async () => structuredClone(data), set: async (patch) => { data = { ...data, ...structuredClone(patch) }; } };
  const jobs = createFillJobs({ storage, identify: async () => ({ documentId: "doc-a" }), prepare: async () => [{ frameId: 0, documentId: "doc-a" }], dispatch: async () => { dispatches++; return [{ filled: 2, total: 2, empty: 0 }]; }, observe: async () => [{ state: "done", result: { filled: 2, total: 2, empty: 0 } }], ...overrides });
  return { jobs, data: () => data, dispatches: () => dispatches };
}
